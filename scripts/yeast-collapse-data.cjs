// Builds the About page's "all sources on one line" chart data (20 Nov 2026) from the
// shipped yeast model and the Phase 3 fit: every dose row of tests/fixtures/yeast-model-data.json,
// its equivalent hours at 25 °C on its own temperature path (app/utils/yeastModel.ts), and its
// dose divided by the medium and rise factors, before and after its source's own level
// (docs/yeast-model/fit3-results.json offsets). tests/yeast-model.test.cjs rebuilds it and
// fails if app/[locale]/about/yeastCollapse.json differs.
//   node scripts/yeast-collapse-data.cjs            (writes the file)
//   require('./scripts/yeast-collapse-data.cjs').build()   (returns the object)
const fs = require('node:fs');
const path = require('node:path');
require('../tests/load-production.cjs');
const m = require('../app/utils/yeastModel.ts');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'app/[locale]/about/yeastCollapse.json');
const GROUP = { rt_mild: 'room', hot: 'hot', cold: 'cold', biga: 'pref', poolish_rt: 'pref', poolish_fridge: 'pref' };
const round = (x, s = 3) => Number(x.toPrecision(s));

function build() {
  const fx = JSON.parse(fs.readFileSync(path.join(ROOT, 'tests/fixtures/yeast-model-data.json'), 'utf8'));
  const fit = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/yeast-model/fit3-results.json'), 'utf8'));
  const medium = { dough: 1, poolish: m.YEAST_MEDIUM_POOLISH, biga: m.YEAST_MEDIUM_BIGA };
  const points = fx.rows.map(r => {
    const p = m.pathHeq(r.T0, r.phases.map(([hours, envC]) => ({ hours, envC, tauH: fx.tauH })));
    const raw = r.dose / (medium[r.medium] * m.riseTarget(p.endC));
    const u = fit.offsets[r.source] ?? 0;
    return { h: round(p.heq), raw: round(raw), adj: round(raw / Math.exp(u)), g: GROUP[r.regime], set: r.set };
  }).sort((a, b) => a.h - b.h || a.adj - b.adj);
  return {
    note: 'Generated by scripts/yeast-collapse-data.cjs from tests/fixtures/yeast-model-data.json and docs/yeast-model/fit3-results.json. h = equivalent hours at 25 °C; raw = instant yeast % / (medium × rise); adj = raw / the source\'s own level.',
    A: m.YEAST_DOSE_A, b: m.YEAST_DOSE_B,
    sigma: round(fit.sigma), tau: round(fit.tau),
    rows: points.length, lineages: new Set(fx.rows.map(r => r.lineage)).size, sources: new Set(fx.rows.map(r => r.source)).size,
    points,
  };
}

if (require.main === module) {
  fs.writeFileSync(OUT, JSON.stringify(build()) + '\n');
  console.log('wrote', path.relative(ROOT, OUT));
}
module.exports = { build, OUT };
