"""Writes tests/fixtures/yeast-model-data.json for tests/yeast-model.test.cjs (Phase 3, 20 Nov 2026).
Every dose row with its stated yeast type, lineage, regime weight, and set (fit / heldout / flagged); the comparisons
are not exported (they need the fit's own machinery). python3 export_fixture3.py OUT.json"""
import json, sys
from data3 import assemble, proof_pairs
from holdout3 import holdout_lineages
HOLDOUT = set(holdout_lineages())
FLAG = json.load(open(sys.argv[2])) if len(sys.argv) > 2 else []
rows, comps, pairs = assemble('regime')
out = []
for r in rows:
    s = 'flagged' if r['id'] in FLAG else ('heldout' if r["lineage"] in HOLDOUT else 'fit')
    out.append({'id': r['id'], 'source': r['source'], 'lineage': r['lineage'], 'yeastType': r['yeast_type'], 'medium': r['medium'],
                'dose': round(r['dose'], 5), 'T0': r['T0'], 'phases': [[h, c] for h, c in r['seg']], 'regime': r['regime'],
                'W': round(r['W'], 5), 'set': s})
json.dump({'note': 'Generated by docs/yeast-model/fit3/export_fixture3.py (Phase 3, 20 Nov 2026). Doses are instant yeast % of the fermenting flour '
                   '(fresh / 3, active dry / 1.33). W = credibility tier in that regime / rows of the lineage. tau 2 h for every data path.',
           'tauH': 2.0, 'holdOutLineages': sorted(HOLDOUT), 'flagged': FLAG, 'rows': out,
           'pairs': [{'ids': list(p['ids']), 'source': p['source'], 'h21': p['h21'], 'h27': p['h27'], 'T0': p['T0']} for p in proof_pairs()]},
          open(sys.argv[1], 'w'), indent=1, ensure_ascii=False)
print(len(out), 'rows')
