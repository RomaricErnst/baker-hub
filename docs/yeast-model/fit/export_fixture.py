"""Writes the data-fit fixture used by tests/yeast-model.test.cjs (shipped constants are checked against it)."""
import json, sys
from rows import load
from fit import PAIRS, NESTEC, PAIR_T0
from holdout import holdout_sources
from run_fit import regime
R = load(); H = set(holdout_sources())
rows = []
for e in R:
    if e['use'] == 'fit' or (e['group'] == 'cold' and e.get('school') == 'community table' and e['use'] in ('fit', 'reference')):
        rows.append({'id': e['id'], 'source': e['source'], 'medium': e['medium'], 'dose': e['dose'], 'T0': e['T0'],
                     'phases': [[h, c] for h, c in e['seg']], 'regime': regime(e),
                     'set': 'community-cold' if (e['group'] == 'cold' and e.get('school') == 'community table') else ('heldout' if e['source'] in H else 'fit')})
pairs = [{'ids': [a['id'], b['id']], 'source': a['source'], 'h21': a['seg'][0][0], 'h27': b['seg'][0][0], 'T0': PAIR_T0} for a, b in PAIRS]
json.dump({'note': 'Generated by S/yeastmodel/fit/export_fixture.py from DATASET.csv (Phase 1, 19 Nov 2026). tau 2 h for every data path.',
           'tauH': 2.0, 'holdOutSources': sorted(H), 'rows': rows, 'pairs': pairs, 'nestec': [{'T': T, 'ratioTo30': r} for T, r in NESTEC]},
          open(sys.argv[1], 'w'), indent=1, ensure_ascii=False)
print(len(rows), 'rows', len(pairs), 'pairs')
